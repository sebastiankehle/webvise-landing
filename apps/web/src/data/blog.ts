export function getBlogPosts(locale: string): BlogPost[] {
	return blogPostsData.map((post) => {
		const lc = post.locales[locale] ?? post.locales["en"];
		return {
			slug: post.slug,
			date: post.date,
			readingTime: post.readingTime,
			keyword: post.keyword,
			title: lc.title,
			excerpt: lc.excerpt,
			blocks: lc.blocks,
		};
	});
}

export function getBlogPostBySlug(
	slug: string,
	locale: string,
): BlogPost | undefined {
	const post = blogPostsData.find((p) => p.slug === slug);
	if (!post) return undefined;
	const lc = post.locales[locale] ?? post.locales["en"];
	return {
		slug: post.slug,
		date: post.date,
		readingTime: post.readingTime,
		keyword: post.keyword,
		title: lc.title,
		excerpt: lc.excerpt,
		blocks: lc.blocks,
	};
}

